/// يحذف أي لقب (د./أ./الأستاذ/الدكتور...) من بداية اسم لأغراض العرض فقط -
/// يُستخدم في كل مكان يظهر فيه اسم شخص (تواصل، أعضاء الوحدة، المرشدين،
/// المنسّقين) حتى يظهر الاسم مجرّدًا دائمًا، بغض النظر عن كيفية كتابته في
/// قاعدة البيانات أو الكود.
String displayName(String raw) {
  return raw
      .trim()
      .replaceFirst(
        RegExp(r'^(الأستاذة|الأستاذ|الدكتورة|الدكتور|أ\.\s*د\.|د\.|أ\.|ا\.|م\.)\s*'),
        '',
      )
      .trim();
}
