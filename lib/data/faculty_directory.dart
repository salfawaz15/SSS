  /// يبحث عن عضو هيئة تدريس/إداري بالاسم (مطابقة تسامحية عبر
  /// [normalizeAdvisorNameForMatch])، ويعيد اسمه وبريده الرسميين كما في
  /// صفحة الجامعة إن وُجد تطابق فريد، أو null إن لم يوجد أو كان الاسم غامضًا
  /// (يطابق أكثر من عضو).
  static (String name, String email)? findByName(String query) {
    final target = normalizeAdvisorNameForMatch(query);
    if (target.isEmpty) return null;
    final matches = entries.where((e) => normalizeAdvisorNameForMatch(e.$1) == target).toList();
    return matches.length == 1 ? matches.first : null;
  }

  /// يبحث عن كل الأسماء التي **تحتوي** (لا تساوي بالضرورة) الكلمات المكتوبة،
  /// لعرضها كاقتراحات أثناء الكتابة (مثل كتابة "محمد" فتظهر كل من يحمل هذا
  /// الاسم ضمن اسمه الرباعي). محدودة بـ 15 اقتراحًا لتفادي إغراق القائمة.
  static Iterable<(String name, String email)> search(String query) {
    final words = normalizeAdvisorNameForMatch(query);
    if (words.isEmpty) return const [];
    return entries.where((e) => normalizeAdvisorNameForMatch(e.$1).contains(words)).take(15);
  }
