/// توحيد اسم القسم العلمي إلى صيغة مرجعية واحدة - يُستخدم في **كل** مصدر
/// يذكر قسمًا (ملف منسوبي الكلية، وتقارير الإرشاد التي تذكر قسم/تخصص
/// الطالب) حتى لا يقارَن قسم الطالب بقسم مرشده كنصّين مختلفين رغم أنهما نفس
/// القسم فعليًا (مثال: "الإدارة" من تقرير الطلاب مقابل "قسم الادارة" من ملف
/// منسوبي الكلية - كانا يُحتسَبان "تعارض قسم" خطأً قبل توحيدهما هنا).
library;

/// الأقسام العلمية الخمسة المعروفة فقط؛ أي جهة أخرى (عمادة الكلية،
/// إدارات...) تبقى كما كُتبت بلا تغيير.
const Map<String, String> _canonicalDepartments = {
  'الادارة': 'قسم الادارة',
  'الإدارة': 'قسم الادارة',
  'المحاسبة': 'قسم المحاسبة',
  'التسويق': 'قسم التسويق',
  'الاقتصاد والتمويل': 'قسم الاقتصاد و التمويل',
  'الاقتصاد و التمويل': 'قسم الاقتصاد و التمويل',
  'نظم المعلومات الادارية': 'قسم نظم المعلومات الادارية',
  'نظم المعلومات الإدارية': 'قسم نظم المعلومات الادارية',
  // تخصصات دقيقة تحت قسم الاقتصاد والتمويل - عمود "التخصص" في تقارير
  // الإرشاد يذكرها بدل اسم القسم مباشرة لهذا القسم تحديدًا.
  'الاقتصاد': 'قسم الاقتصاد و التمويل',
  'تمويل': 'قسم الاقتصاد و التمويل',
  'التمويل': 'قسم الاقتصاد و التمويل',
  'التأمين وإدارة المخاطر': 'قسم الاقتصاد و التمويل',
  'التامين وادارة المخاطر': 'قسم الاقتصاد و التمويل',
};

/// مفتاح مطابقة متسامح: يطوي كل المسافات ويوحّد صور الهمزة - حتى لا يظهر
/// القسم نفسه "شبحيًا" كقسم مختلف فقط لأن خلية واحدة كُتبت بمسافة إضافية أو
/// همزة مختلفة عن بقية الصفوف.
String _looseKey(String s) => s.trim().replaceAll(RegExp(r'\s+'), '').replaceAll(RegExp('[أإآ]'), 'ا');

/// بعض الملفات تكتب عبارة الشطر ملتصقة بنص القسم/الجهة نفسه
/// ("قسم الإدارة - شطر الطلاب") بدل عمود الشطر المخصص لذلك - تُزال قبل التوحيد.
String _stripAttachedShatr(String s) =>
    s.replaceAll(RegExp(r'\s*[-–]?\s*ب?شطر\s*(الطلاب|الطالبات)\s*'), '').trim();

/// بعض الملفات تكتب اسم القسم مسبوقًا بكلمة "قسم" وبعضها بدونها - نزيلها
/// دائمًا قبل المطابقة مع [_canonicalDepartments] (مفاتيحها كلها بلا "قسم").
String _stripLeadingQism(String s) => s.trim().replaceFirst(RegExp(r'^قسم\s+'), '').trim();

/// يوحّد صيغة اسم القسم إلى الصيغة الرسمية "قسم X" بغض النظر عن وجود كلمة
/// "قسم"، اختلاف صور الهمزة، أو عبارة شطر ملتصقة بالنص.
String normalizeDepartmentName(String raw) {
  final trimmed = _stripAttachedShatr(raw.trim());
  final loose = _looseKey(_stripLeadingQism(trimmed));
  for (final entry in _canonicalDepartments.entries) {
    if (_looseKey(entry.key) == loose) return entry.value;
  }
  return trimmed;
}

/// الأقسام العلمية الخمسة (بكالوريوس) فقط - أي قسم/برنامج آخر (مثال: "إدارة
/// الأعمال التنفيذي" برنامج ماجستير تنفيذي) ليس منها.
final Set<String> knownBachelorDepartments = _canonicalDepartments.values.toSet();

/// هل [normalizedDepartment] (ناتج [normalizeDepartmentName]) أحد الأقسام
/// العلمية الخمسة المعروفة؟ يُستخدم لاستبعاد برامج الدراسات العليا التي قد لا
/// يحمل عمود "الدرجة العلمية" فيها كلمة "ماجستير"/"دكتوراه" بشكل موثوق (مثال:
/// "إدارة الأعمال التنفيذي") - القسم نفسه غير معروف كقسم بكالوريوس فيُستبعَد.
bool isKnownBachelorDepartment(String normalizedDepartment) =>
    knownBachelorDepartments.contains(normalizedDepartment);

/// برنامج "إدارة الأعمال التنفيذي" (ماجستير تنفيذي) - سليمان طلب صراحةً
/// (2026-08-14) استبعاد أي طالب/ة فيه من كل الإحصائيات والإرشاد كليًا، أيًا
/// كان مرشده ووضعه، لا فقط تصنيفه كـ"طالب خارجي". يُطابَق على النص الخام قبل
/// التوحيد لأن هذا البرنامج ليس أحد الأقسام الخمسة أصلًا فلا يمر بالتوحيد.
bool isExecutiveMbaProgram(String rawDepartment) =>
    _looseKey(rawDepartment).contains(_looseKey('الأعمال التنفيذي'));
